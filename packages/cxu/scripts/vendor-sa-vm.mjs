import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = dirname(here);
const repoRoot = dirname(dirname(pkgRoot));
const serverSrc = join(repoRoot, "apps", "server", "src");
const sdkSrc = join(repoRoot, "sdk-backend", "src");
// saVmJev.ts lives in the cxu-backend-jev plugin project and
// saVmPolicy.ts in cxu-backend-vmtool-security. Their vendored copies
// keep the flat layout and local imports (patched in patchSource).
const SOURCE_DIRS = {
  "saVmJev.ts": join(repoRoot, "backends", "jev", "src", "jev"),
  "saVmPolicy.ts": join(repoRoot, "backends", "vmtool-security", "src", "security"),
};
const vendorDir = join(pkgRoot, "src", "vendor");

const SOURCES = [
  "saVmTool.ts",
  "saVmJev.ts",
  "saVmPolicy.ts",
  "saVmApplyPatch.ts",
  "saVmProcess.ts",
  "saVmRequest.ts",
  "saVmResultKind.ts",
  "saVmTreeSitter.ts",
  "saVmCodeGraph.ts",
  "saVmAccountabilityLedger.ts",
];

// SDK modules the vendored graph depends on (R2: SA-VM protocol types,
// memory file paths, regression case loading, data dir). Copied flat
// and re-exported through the generated sdk-backend.ts barrel, so
// vendored sources keep calling the SDK surface — no per-symbol
// patching, no local re-implementation stubs.
const SDK_SOURCES = [
  "saVmTypes.ts",
  "memoryFilePaths.ts",
  "regressionCases.ts",
  "dataDir.ts",
];

const SDK_BARREL = `// Generated by scripts/vendor-sa-vm.mjs: the vendored stand-in for
// "@cxu/sdk-backend", re-exporting the copied SDK modules flat.
export * from "./saVmTypes.js";
export * from "./memoryFilePaths.js";
export * from "./regressionCases.js";
export * from "./dataDir.js";
`;

/**
 * The ONLY import-specifier rewrites left (R2): package specifiers and
 * cross-project plugin paths become flat siblings inside the vendor
 * tree. Everything else about the sources is copied verbatim, and the
 * guard below fails the vendoring if any cross-boundary specifier
 * survives — a missed mapping is a build error, never a silent stub.
 */
function patchSource(name, text) {
  let out = text;
  out = out.replaceAll('from "@codex-ui/shared"', 'from "../shared-types.js"');
  out = out.replaceAll('from "@cxu/sdk-backend"', 'from "./sdk-backend.js"');
  out = out.replaceAll(
    'from "../../../backends/jev/src/jev/saVmJev.js"',
    'from "./saVmJev.js"',
  );
  out = out.replaceAll(
    'from "../../../backends/vmtool-security/src/security/saVmPolicy.js"',
    'from "./saVmPolicy.js"',
  );
  if (name === "saVmTreeSitter.ts") {
    // Asset layout, not imports: wasm files ship beside the bundle.
    out = out.replaceAll(
      'join(currentDir, "node_modules", "web-tree-sitter", "tree-sitter.wasm")',
      'join(currentDir, "../wasm", "tree-sitter.wasm")',
    );
    out = out.replaceAll(
      'join(currentDir, "node_modules", "tree-sitter-wasms", "out", fileName)',
      'join(currentDir, "../wasm", "languages", fileName)',
    );
    out = out.replaceAll(
      'join(currentDir, "../node_modules", "tree-sitter-wasms", "out", fileName)',
      'join(currentDir, "../../wasm", "languages", fileName)',
    );
    out = out.replaceAll(
      'join(currentDir, "../../node_modules", "tree-sitter-wasms", "out", fileName)',
      'join(currentDir, "../../../wasm", "languages", fileName)',
    );
  }
  for (const match of out.matchAll(/(?:from|import)\s*["']([^"']+)["']/g)) {
    const specifier = match[1];
    if (
      specifier.includes("apps/") ||
      specifier.includes("backends/") ||
      specifier.startsWith("@cxu/") ||
      specifier.startsWith("@codex-ui/")
    ) {
      throw new Error(`${name}: unpatched cross-boundary import "${specifier}"`);
    }
  }
  return out;
}

await mkdir(vendorDir, { recursive: true });
for (const name of SOURCES) {
  const raw = await readFile(join(SOURCE_DIRS[name] ?? serverSrc, name), "utf8");
  await writeFile(join(vendorDir, name), patchSource(name, raw), "utf8");
  console.log(`vendored ${name}`);
}
for (const name of SDK_SOURCES) {
  const raw = await readFile(join(sdkSrc, name), "utf8");
  await writeFile(join(vendorDir, name), patchSource(name, raw), "utf8");
  console.log(`vendored sdk ${name}`);
}
await writeFile(join(vendorDir, "sdk-backend.ts"), SDK_BARREL, "utf8");
console.log("vendored sdk-backend.ts barrel");
