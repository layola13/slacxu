import { randomUUID } from "node:crypto";
import { mkdir, rename, writeFile } from "node:fs/promises";
import { statSync } from "node:fs";
import { join } from "node:path";

/**
 * Thrown when Cursor.exe is not at the expected location. Callers (web UI,
 * CLI script) turn this into a prompt so the user can enter the real path —
 * installs outside %LOCALAPPDATA% are deliberately not auto-discovered.
 */
export const CURSOR_INSTALL_DIR_NOT_FOUND_CODE = "cursorInstallDirNotFound";

export class CursorInstallDirNotFoundError extends Error {
  readonly searchedPath: string;

  constructor(searchedPath: string) {
    super(`Cursor.exe was not found in ${searchedPath}; please enter the Cursor installation directory manually`);
    this.name = "CursorInstallDirNotFoundError";
    this.searchedPath = searchedPath;
  }
}

export type CursorDesktopInjectionInput = {
  baseUrl: string;
  token: string;
  installDir?: string;
  platform?: NodeJS.Platform;
};

export function resolveCursorInstallDir(options: {
  localAppData?: string;
  installDir?: string;
} = {}): string {
  // Explicit paths are validated as-is; anything else must contain Cursor.exe.
  const explicit = options.installDir?.trim();
  if (explicit) {
    if (!defaultFileExists(join(explicit, "Cursor.exe"))) {
      throw new CursorInstallDirNotFoundError(join(explicit, "Cursor.exe"));
    }
    return explicit;
  }
  const localAppData = options.localAppData ?? process.env.LOCALAPPDATA ?? "";
  if (!localAppData.trim()) throw new CursorInstallDirNotFoundError("%LOCALAPPDATA%");
  const defaultDir = join(localAppData, "Programs", "cursor");
  if (!defaultFileExists(join(defaultDir, "Cursor.exe"))) {
    throw new CursorInstallDirNotFoundError(defaultDir);
  }
  return defaultDir;
}

function defaultFileExists(path: string): boolean {
  try {
    statSync(path);
    return true;
  } catch {
    return false;
  }
}

/**
 * Cursor's local mode ("Connect Cursor to a compatible LLM Gateway or API")
 * reads its gateway endpoint and credential from launch-time environment
 * variables instead of any on-disk config, so the injection is a generated
 * launcher that sets them and starts Cursor with --local-mode.
 */
export async function writeCursorRelayLauncher(input: CursorDesktopInjectionInput): Promise<{
  launcherPath: string;
  exePath: string;
}> {
  const baseUrl = input.baseUrl.trim().replace(/\/+$/, "");
  const token = input.token.trim();
  if (!baseUrl || !token) {
    throw new Error("Cursor Desktop injection requires a gateway URL and token");
  }
  if ((input.platform ?? process.platform) !== "win32") {
    throw new Error("Cursor Desktop injection is only available on Windows");
  }
  const installDir = resolveCursorInstallDir({ installDir: input.installDir });
  const exePath = join(installDir, "Cursor.exe");
  const launcherDir = join(installDir, "..", "cursor-relay");
  const launcherPath = join(launcherDir, "cursor-relay-launcher.cmd");
  const temporaryPath = `${launcherPath}.${randomUUID()}.tmp`;
  await mkdir(launcherDir, { recursive: true });
  await writeFile(temporaryPath, [
    "@echo off",
    "rem Generated by codex-ultra Cursor relay injection; edits are overwritten on re-inject.",
    `set "CURSOR_LOCAL_AGENT_BASE_URL=${baseUrl}"`,
    `set "CURSOR_LOCAL_AGENT_API_KEY=${token}"`,
    `start "" "${exePath}" --local-mode`,
    ""
  ].join("\r\n"), { encoding: "utf8" });
  await rename(temporaryPath, launcherPath);
  return { launcherPath, exePath };
}
